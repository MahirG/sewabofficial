export function localizePackage(
  travelPackage: TravelPackage,
  language: AppLanguage,
): PackageTranslation {
  if (language === "en" || language === "am") {
    return {
      title: travelPackage.title[language],
      duration: travelPackage.duration[language],
      description: travelPackage.description[language],
      location: travelPackage.location[language],
      features: travelPackage.features.map((feature) => feature[language]),
    };
  }

  return packageTranslations[language][travelPackage.id] ?? {
    title: travelPackage.title.en,
    duration: travelPackage.duration.en,
    description: travelPackage.description.en,
    location: travelPackage.location.en,
    features: travelPackage.features.map((feature) => feature.en),
  };
}

export function getLanguageOption(language: AppLanguage) {
  return languageOptions.find((option) => option.code === language) ?? languageOptions[0];
}
